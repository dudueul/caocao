/**
 * Chapter 2 (여포) scenes and camps, staged on tile maps (ADR 0063). The two
 * choices live here: 서주 (`xuzhou`: revenge / mercy) and 백문루 (`lubu`:
 * executed / spared); 전위's fate (`dianwei`: lived / fell) is decided at
 * 완성 (ADR 0060, 0061). Every scene plays on every path: 진궁 stands with
 * us only after mercy, 전위 lives or dies after 완성, and 여포 or 장료 stands
 * in the last scene. Our own words, maps and blocking throughout (ADR 0002).
 *
 * Staging conventions: an actor who speaks has the speaker's officer id as
 * its id (the player finds the speaker by id); a second actor for the same
 * person (진궁 in 여포's colours, 조조 on his son's horse) never speaks.
 * Extras are named after their army (`cao-s1`), so they wear its look.
 */
