// ---------------------------------------------------------------- small helpers

type At = [number, number];

const light = (l: StageLight): Cmd => ({ do: "light", light: l });
/** One command, only when `c` holds. */
const on = (c: Cond, cmd: Cmd): Cmd => ({ ...cmd, if: c });
/** A line from the other side: 여포's men, 장수's, 원술's, 원소. */
const foe = (who: string, text: string, mood?: Mood, extra: Partial<Line> = {}): Cmd =>
  say(who, text, mood, { side: 1, ...extra });
/** A line from 유비 and his brothers, who fight beside us at 하비. */
const ally = (who: string, text: string, mood?: Mood): Cmd => say(who, text, mood, { side: 0 });
/** An extra in an army's colours (or a second figure for an officer). */
const extra = (
  id: string,
  officer: string,
  side: number,
  at?: At,
  facing?: Facing4,
  more: Partial<Actor> = {},
): Actor => actor(id, side, at, facing, { officer, ...more });
const prop = (kind: PropKind, x: number, y: number, more: Partial<PropDef> = {}): PropDef => ({
  kind,
  at: { x, y },
  ...more,
});
const cells = (...xy: At[]): Cell[] => xy.map(([x, y]) => ({ x, y }));
const each = (ids: readonly string[], f: (id: string) => Cmd): Cmd => all(...ids.map(f));

