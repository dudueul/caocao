#!/usr/bin/env python3
"""seed_items.py — seed the D1 items catalog from seed/items.json.
Usage: seed_items.py   (run from server/ with wrangler available)
"""
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
items = json.load(open(os.path.join(HERE, "seed", "items.json")))

cols = ["item_id", "name", "tier", "slot", "item_type", "box_type", "price", "gold",
        "item_effect", "effect_value", "max_value", "type_value", "pay_type",
        "atk", "atk_up", "def", "def_up", "inte", "inte_up", "agi", "agi_up",
        "mor", "mor_up", "hp", "hp_up", "mp", "mp_up", "max_lv", "target_type",
        "skill_id", "unit_id", "atlas", "icon", "country", "job_type"]
# camelCase source keys -> snake cols
alias = {"tresure_type": "tresure_type"}
rows = []
for it in items:
    vals = []
    for col in cols:
        v = it.get(col, it.get(col.replace("_", ""), 0))
        if isinstance(v, str):
            v = v.replace("'", "''")
            vals.append(f"'{v}'")
        else:
            vals.append(str(v))
    rows.append(f"INSERT OR REPLACE INTO items ({','.join(cols)}) VALUES ({','.join(vals)});")

sql = "-- generated by seed_items.py\n" + "\n".join(rows) + "\n"
open(os.path.join(HERE, "seed", "items.sql"), "w").write(sql)
print(f"wrote seed/items.sql with {len(rows)} items")
for f in (os.path.join(HERE, "schema.d1.sql"), os.path.join(HERE, "seed", "items.sql")):
    subprocess.run([os.path.expanduser("~/.local/share/fnm/node-versions/v26.2.0/installation/bin/npx"),
                    "wrangler", "d1", "execute", "caocao", "--local",
                    "--file", f], check=False)
print("seeded (wrangler d1 local)")
