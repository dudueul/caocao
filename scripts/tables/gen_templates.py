"""Generate the 239 data-table templates, pre-filled from Localization_0.txt.

Inputs (all in --work): schema.json, load_order.json, alignment.json, anchors.json
Outputs (--out): schema.json, TABLES.md, localization_index.csv,
                 templates/<Table>.csv, templates/<Table>.strings.csv
"""
import argparse, csv, json, os, re, collections

ap = argparse.ArgumentParser()
ap.add_argument('--work', required=True)
ap.add_argument('--loc', required=True)
ap.add_argument('--out', required=True)
a = ap.parse_args()

schema = json.load(open(os.path.join(a.work, 'schema.json'), encoding='utf-8'))
order = json.load(open(os.path.join(a.work, 'load_order.json')))['PermanentData$$Reload']
al = json.load(open(os.path.join(a.work, 'alignment.json'), encoding='utf-8'))
anchors = json.load(open(os.path.join(a.work, 'anchors.json')))
rows = list(csv.reader(open(a.loc, encoding='utf-8-sig')))
header, rows = rows[0], rows[1:]
EN = header.index('English')

slots = [tuple(s) for s in al['slots']]
assign = al['assign']

# confidence: a row is "anchored" when it lies between two anchors of its own slot
by_slot = collections.defaultdict(list)
for r, key in anchors:
    by_slot[key].append(r)
spans = {k: (min(v), max(v)) for k, v in by_slot.items()}
def confidence(r, t, c):
    if t == '__UI__':
        return 'ui'
    sp = spans.get(f'{t}.{c}')
    return 'anchored' if sp and sp[0] <= r <= sp[1] else 'inferred'

ASSET = re.compile(r'(atlas|icon|prefab|image|img|fx|sfx|^se$|SE$|snd|sound$|bgm|texture|sprite|anim|file|path|loader|^scene$|color|marker|thumbnail|emblem|^face$)', re.I)
def kind(col):
    t = col['type']
    if t in ('string', 'List<string>'):
        return 'asset' if ASSET.search(col['name']) else 'text'
    return 'list' if t.startswith('List<') else 'number'

strings = collections.defaultdict(lambda: collections.defaultdict(list))   # table -> column -> [(row, conf)]
index_rows = []
for r, s in enumerate(assign):
    t, c, _ = slots[s]
    conf = confidence(r, t, c)
    index_rows.append((r + 2, t, c, conf))          # +2: 1-based line incl. header
    if t != '__UI__':
        strings[t][c].append((r, conf))

os.makedirs(os.path.join(a.out, 'templates'), exist_ok=True)
load_pos = {t: i for i, t in enumerate(order)}
summary = []
for tb in schema:
    t = tb['table']
    cols = tb['columns']
    for c in cols:
        c['kind'] = kind(c)
    tb['loadOrder'] = load_pos.get(t)
    filled = strings.get(t, {})
    text_cols = [c['name'] for c in cols if c['kind'] == 'text']
    prim = next((c for c in text_cols if filled.get(c)), None)
    n_rows = len(filled[prim]) if prim else 0
    paired = [c for c in text_cols if c != prim and filled.get(c) and len(filled[c]) == n_rows]
    # template
    hdr = [c['name'] for c in cols]
    helpers = []
    if prim:
        helpers = [f'#{prim}_en'] + [f'#{c}_en' for c in paired] + ['#loc_row', '#confidence']
    with open(os.path.join(a.out, 'templates', f'{t}.csv'), 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f)
        w.writerow(hdr + helpers)
        for i in range(n_rows):
            rec = {c: '' for c in hdr}
            r0, conf0 = filled[prim][i]
            rec[prim] = rows[r0][0]
            ens = [rows[r0][EN]]
            confs = {conf0}
            for c in paired:
                rp, cp = filled[c][i]
                rec[c] = rows[rp][0]
                ens.append(rows[rp][EN])
                confs.add(cp)
            conf = 'anchored' if confs == {'anchored'} else 'inferred'
            w.writerow([rec[c] for c in hdr] + ens + [r0 + 2, conf])
    # sidecar with every candidate string per text column
    if filled:
        with open(os.path.join(a.out, 'templates', f'{t}.strings.csv'), 'w', encoding='utf-8', newline='') as f:
            w = csv.writer(f)
            w.writerow(['column', 'seq', 'loc_row', 'confidence', 'ko', 'en'])
            for c in [c['name'] for c in cols]:
                for i, (r, conf) in enumerate(filled.get(c, [])):
                    w.writerow([c, i + 1, r + 2, conf, rows[r][0], rows[r][EN]])
    tb['prefill'] = {'primaryColumn': prim, 'rows': n_rows, 'pairedColumns': paired,
                     'stringsPerColumn': {c: len(v) for c, v in filled.items()},
                     'anchoredStrings': sum(1 for v in filled.values() for _, cf in v if cf == 'anchored')}
    summary.append(tb)

json.dump(summary, open(os.path.join(a.out, 'schema.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
with open(os.path.join(a.out, 'localization_index.csv'), 'w', encoding='utf-8', newline='') as f:
    w = csv.writer(f)
    w.writerow(['loc_line', 'table', 'column', 'confidence'])
    w.writerows(index_rows)

# TABLES.md
lines = ['# Data-table index (239 baked tables)', '',
         'Generated by `scripts/tables/gen_templates.py`. Column order = serialized field order of the raw',
         '`__Row` class (what the baked ScriptableObject stores). `kind`: text = localized Korean key,',
         'asset = resource name, number/list = values to author. Load order = position in `PermanentData.Reload`.', '',
         '| # | Table | Load | Columns | Pre-filled rows | Strings (anchored / total) |', '|---|---|---|---|---|---|']
for i, tb in enumerate(sorted(summary, key=lambda x: (x['loadOrder'] is None, x['loadOrder'] or 0))):
    p = tb['prefill']
    tot = sum(p['stringsPerColumn'].values())
    lines.append(f"| {i+1} | [{tb['table']}](templates/{tb['table']}.csv) | {tb['loadOrder'] if tb['loadOrder'] is not None else '—'} | {len(tb['columns'])} | {p['rows']} | {p['anchoredStrings']} / {tot} |")
lines += ['', '## Columns per table', '']
for tb in sorted(summary, key=lambda x: x['table']):
    lines.append(f"### {tb['table']}")
    lines.append(f"raw `{tb['rawClass']}` (TypeDefIndex {tb['rawTypeDefIndex']}) → row `{tb['rawRowClass']}` ({tb['rawRowTypeDefIndex']}); refined `{tb['refinedClass']}` / `{tb['refinedRowClass']}`")
    lines.append('')
    lines.append(', '.join(f"`{c['name']}`:{c['type']}{'*' if c['kind']=='text' else ''}" for c in tb['columns']))
    lines.append('')
open(os.path.join(a.out, 'TABLES.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
tot_rows = sum(t['prefill']['rows'] for t in summary)
tot_str = sum(sum(t['prefill']['stringsPerColumn'].values()) for t in summary)
anch = sum(t['prefill']['anchoredStrings'] for t in summary)
print(f'tables {len(summary)}, prefilled tables {sum(1 for t in summary if t["prefill"]["rows"])}, template rows {tot_rows}, strings {tot_str} (anchored {anch}), ui rows {sum(1 for x in index_rows if x[1]=="__UI__")}')
