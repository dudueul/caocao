using LitJson;

public static class JsonDataExtensions
{
	public static int ToInt(this JsonData self)
	{
		return 0;
	}

	public static uint ToUInt(this JsonData self)
	{
		return 0u;
	}

	public static short ToShort(this JsonData self)
	{
		return 0;
	}

	public static ushort ToUShort(this JsonData self)
	{
		return 0;
	}

	public static long ToLong(this JsonData self)
	{
		return 0L;
	}

	public static ulong ToULong(this JsonData self)
	{
		return 0uL;
	}

	public static float ToFloat(this JsonData self)
	{
		return 0f;
	}

	public static double ToDouble(this JsonData self)
	{
		return 0.0;
	}

	public static bool ToBool(this JsonData self)
	{
		return false;
	}
}
